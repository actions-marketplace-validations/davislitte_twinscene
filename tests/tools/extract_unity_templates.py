"""Copies one object of each class TwinScene creates out of a scene Unity saved, into twinscene/unity/templates.yaml.

New objects then start from exactly what Unity writes. Re-run after regenerating the reference scene with the oldest
Unity version TwinScene supports:  python tests/tools/extract_unity_templates.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from twinscene.unity import yaml  # noqa: E402

SCENE = ROOT / "tests/projects/unity_ref/Assets/Scenes/Reference.unity"
OUT = ROOT / "twinscene/unity/templates.yaml"
EMPTY_SCENE = ROOT / "twinscene/unity/empty_scene.unity"
MATERIAL = ROOT / "twinscene/unity/material.mat"
SETTINGS = [29, 104, 157, 196]  # OcclusionCullingSettings, RenderSettings, LightmapSettings, NavMeshSettings
# GameObject, Transform, Camera, MeshRenderer, MeshFilter, Rigidbody, BoxCollider, Light, SphereCollider, CapsuleCollider
CLASSES = [1, 4, 20, 23, 33, 54, 65, 108, 135, 136]


def main():
    doc = yaml.loads(SCENE.read_text(encoding="utf-8"))
    version = (SCENE.parents[2] / "ProjectSettings/ProjectVersion.txt").read_text().splitlines()[0].split(": ")[1]
    out = [
        "%YAML 1.1",
        "%TAG !u! tag:unity3d.com,2011:",
        f"# Generated by tests/tools/extract_unity_templates.py from a scene saved by Unity {version}.",
        "# Each object's file id is its class id; the writer replaces ids and every field it knows.",
    ]
    for cid in CLASSES:
        obj = next(o for o in doc.objects if o.class_id == cid and not o.stripped)
        lines = list(obj.lines)
        lines[0] = f"--- !u!{cid} &{cid}"
        out += lines
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} from Unity {version}")

    # A new scene: Unity's header and settings objects, and no GameObjects.
    empty = list(doc.header)
    for cid in SETTINGS:
        empty += next(o for o in doc.objects if o.class_id == cid).lines
    empty += ["--- !u!1660057539 &9223372036854775807", "SceneRoots:", "  m_ObjectHideFlags: 0", "  m_Roots: []"]
    EMPTY_SCENE.write_text("\n".join(empty) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {EMPTY_SCENE.relative_to(ROOT)}")

    # A material (built-in Standard shader); the writer switches the shader for URP projects.
    mat = (SCENE.parents[1] / "Materials/BoxRed.mat").read_text(encoding="utf-8")
    MATERIAL.write_text(mat, encoding="utf-8", newline="\n")
    print(f"wrote {MATERIAL.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
